# Run from the package root: Rscript data-raw/fonts.R
version <- "5.3.0"
families <- c(
  "alegreya-sans-sc",
  "bangers",
  "berkshire-swash",
  "cardo",
  "dosis",
  "ibm-plex-sans",
  "inconsolata",
  "open-sans",
  "oswald",
  "raleway",
  "roboto",
  "roboto-condensed",
  "shadows-into-light",
  "signika",
  "unica-one"
)

rebuild_fonts <- function() {
  stopifnot(file.exists("data-raw/fonts.R"), dir.exists("inst"))
  work <- tempfile("fontsource-")
  stage <- tempfile("fonts-", tmpdir = "inst")
  dir.create(work)
  dir.create(stage)
  on.exit(unlink(c(work, stage), recursive = TRUE))

  rules <- vapply(
    families,
    function(family) {
      message("Fetching ", family)
      url <- sprintf(
        "https://registry.npmjs.org/@fontsource/%s/-/%s-%s.tgz",
        family,
        family,
        version
      )
      archive <- file.path(work, paste0(family, ".tgz"))
      download.file(url, archive, mode = "wb", quiet = TRUE)
      face <- paste0(family, "-latin-400-normal.woff2")
      font_file <- file.path("files", face)
      files <- file.path("package", c("400.css", "LICENSE", font_file))
      source <- file.path(work, family)
      dir.create(source)
      utils::untar(archive, files = files, exdir = source)
      package_dir <- file.path(source, "package")

      target <- file.path(stage, family)
      dir.create(target)
      stopifnot(file.copy(file.path(package_dir, "LICENSE"), target))
      stopifnot(file.copy(
        file.path(package_dir, font_file),
        file.path(target, "latin.woff2")
      ))

      # Keep Fontsource's Unicode range so other scripts can use a fallback.
      css <- paste(
        readLines(
          file.path(package_dir, "400.css"),
          encoding = "UTF-8",
          warn = FALSE
        ),
        collapse = "\n"
      )
      blocks <- strsplit(css, "\n\n", fixed = TRUE)[[1]]
      latin <- blocks[grepl(paste0("/", face, ")"), blocks, fixed = TRUE)]
      stopifnot(
        length(latin) == 1L,
        grepl("unicode-range:", latin, fixed = TRUE)
      )
      sub(
        "src: [^\n]+",
        sprintf("src: url(%s/latin.woff2) format('woff2');", family),
        latin
      )
    },
    character(1)
  )
  header <- sprintf(
    "/* Generated by data-raw/fonts.R from Fontsource %s. */",
    version
  )
  writeLines(
    paste(c(header, rules), collapse = "\n\n"),
    file.path(stage, "fonts.css"),
    useBytes = TRUE
  )

  # Publish the complete collection only after all downloads succeed.
  target <- file.path("inst", "fonts")
  backup <- tempfile("previous-fonts-", tmpdir = "inst")
  if (dir.exists(target)) {
    stopifnot(file.rename(target, backup))
  }
  if (!file.rename(stage, target)) {
    if (dir.exists(backup)) {
      stopifnot(file.rename(backup, target))
    }
    stop("Could not replace ", target)
  }
  unlink(backup, recursive = TRUE)
}

rebuild_fonts()
