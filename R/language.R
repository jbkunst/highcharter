#' Set the default language for Highcharts widgets
#'
#' `hc_set_language()` sets the `highcharter.lang` option for charts created
#' afterwards in the current R process. `hc_language()` builds a language
#' list with the same arguments and leaves the current option unchanged.
#'
#' @param locale Use a language code: `"en"` (English), `"es"` (Spanish),
#'   `"pt"` (Portuguese), `"fr"` (French), `"nb"` (Norwegian Bokmål),
#'   `"ja"` (Japanese), `"ko"` (Korean),
#'   or `"zh-CN"` (Simplified Chinese). A region is optional: `"es-MX"`
#'   uses the same Spanish labels as `"es"` with Mexican date and number
#'   formatting. Other languages use English labels and their own formatting.
#' @param ... Named Highcharts `lang` options to override, including nested
#'   lists such as `exportData = list(categoryHeader = "Product")`.
#' @return `hc_language()` returns a Highcharts `lang` list.
#'   `hc_set_language()` invisibly returns the previous option.
#' @details The Spanish and Portuguese presets cover common chart controls, downloads,
#'   Stock range selection and basic accessibility labels. Highcharts supplies
#'   the English defaults and the French, Norwegian Bokmål and Simplified Chinese
#'   language packs.
#'   Japanese and Korean interface labels are AI-generated translations maintained
#'   in highcharter, not official Highcharts translations. Untranslated controls
#'   fall back to English. Dates use the browser's built-in `Intl` formatting via
#'   `lang.locale`; those date translations are not generated by AI. Chart titles
#'   and series names are supplied by the author and are not translated.
#'   Traditional Chinese locales currently use English interface labels.
#'   See \url{https://www.highcharts.com/docs/advanced-chart-features/internationalization}.
#' @examples
#' hc_language("es-CL")$locale
#' old <- hc_set_language("es-CL")
#' hchart(AirPassengers) |> hc_exporting(enabled = TRUE)
#' options(old)
#' @export
hc_language <- function(locale = "en", ...) {
  if (
    !is.character(locale) ||
      length(locale) != 1L ||
      is.na(locale) ||
      !grepl("^[A-Za-z]{2,3}(-[A-Za-z]{4})?(-([A-Za-z]{2}|[0-9]{3}))?$", locale)
  ) {
    stop(
      "Use a language code such as 'en', 'es', 'pt', 'fr', 'nb', 'ja', 'ko' or 'zh-CN', optionally with a region.",
      call. = FALSE
    )
  }
  code <- tolower(sub("-.*", "", locale))
  lang <- list()
  simplified_chinese <- tolower(locale) %in%
    c("zh", "zh-cn", "zh-sg", "zh-hans", "zh-hans-cn", "zh-hans-sg")
  if (code %in% c("es", "pt", "fr", "nb", "ja", "ko") || simplified_chinese) {
    path <- system.file(
      "lang",
      paste0(code, ".json"),
      package = "highcharter",
      mustWork = TRUE
    )
    lang <- jsonlite::fromJSON(path)
  }
  lang$locale <- locale
  overrides <- list(...)
  if (
    length(overrides) &&
      (is.null(names(overrides)) || any(!nzchar(names(overrides))))
  ) {
    stop("Name each Highcharts lang override.", call. = FALSE)
  }
  .merge_options(lang, overrides, keep_null = TRUE)
}

#' @rdname hc_language
#' @export
hc_set_language <- function(locale, ...) {
  options(highcharter.lang = hc_language(locale, ...))
}
